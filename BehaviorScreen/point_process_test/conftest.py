def make_scaffold_dataset(
    num_fish: int, num_trials: int, duration_s: float, binning_dt: float = 0.05
) -> PointProcessDataset:
    """
    An EMPTY dataset shell (no events yet) with every (fish, trial) marked
    active -- provides the (duration_s, mask, ids) context simulate_stream
    needs, before any events exist to put in it.
    """
    return PointProcessDataset(
        event_times=np.array([], dtype=float),
        event_trials_idx=np.array([], dtype=int),
        event_fish_idx=np.array([], dtype=int),
        fish_trial_mask=np.ones((num_fish, num_trials), dtype=bool),
        fish_ids=np.array([f"fish_{i}" for i in range(num_fish)]),
        duration_s=duration_s,
        binning_dt=binning_dt,
    )


def simulate_dataset_from_model(
    model,
    scaffold: PointProcessDataset,
    rng: np.random.Generator,
    fish_gains: Optional[np.ndarray] = None,
) -> PointProcessDataset:
    """
    Simulate a full dataset by calling model.simulate_stream(scaffold, t_idx,
    gain, rng) for every active (fish, trial) pair in `scaffold`.

    PRECONDITION: model.set_params(...) must already have been called with
    the parameters you want to simulate FROM -- every simulate_stream
    implementation in this codebase reads self.params_ internally, not an
    explicit argument.

    fish_gains: optional (num_fish,) array of per-fish multiplicative gain
    draws (a frailty realization), SHARED across all of that fish's trials
    -- matching the modeling assumption that g_f is a fish-level, not a
    fish-trial-level, random effect. Defaults to gain=1 for every fish (no
    frailty).
    """
    if fish_gains is None:
        fish_gains = np.ones(scaffold.num_fish)

    times, trials, fish = [], [], []
    for f_idx in range(scaffold.num_fish):
        for t_idx in range(scaffold.num_trials):
            if not scaffold.fish_trial_mask[f_idx, t_idx]:
                continue
            ev = model.simulate_stream(scaffold, t_idx, float(fish_gains[f_idx]), rng)
            if len(ev):
                times.append(np.asarray(ev, dtype=float))
                trials.append(np.full(len(ev), t_idx, dtype=int))
                fish.append(np.full(len(ev), f_idx, dtype=int))

    event_times = np.concatenate(times) if times else np.array([], dtype=float)
    event_trials_idx = np.concatenate(trials) if trials else np.array([], dtype=int)
    event_fish_idx = np.concatenate(fish) if fish else np.array([], dtype=int)

    return PointProcessDataset(
        event_times=event_times,
        event_trials_idx=event_trials_idx,
        event_fish_idx=event_fish_idx,
        fish_trial_mask=scaffold.fish_trial_mask,
        fish_ids=scaffold.fish_ids,
        duration_s=scaffold.duration_s,
        binning_dt=scaffold.binning_dt,
    )


def dataset_from_streams(
    streams: List[List[np.ndarray]], duration_s: float, num_trials: int
) -> PointProcessDataset:
    """
    Build a PointProcessDataset from a nested list `streams[fish_idx][trial_idx]
    -> event_times array` -- used by Layer 2's independent-simulator tests,
    which don't go through simulate_dataset_from_model at all (that helper
    calls model.simulate_stream; Layer 2 deliberately avoids the model
    entirely on the generation side).
    """
    times, trials, fish = [], [], []
    for f_idx, per_trial_events in enumerate(streams):
        for t_idx, ev in enumerate(per_trial_events):
            if len(ev):
                times.append(np.asarray(ev, dtype=float))
                trials.append(np.full(len(ev), t_idx, dtype=int))
                fish.append(np.full(len(ev), f_idx, dtype=int))
    return PointProcessDataset(
        event_times=np.concatenate(times) if times else np.array([], dtype=float),
        event_trials_idx=np.concatenate(trials) if trials else np.array([], dtype=int),
        event_fish_idx=np.concatenate(fish) if fish else np.array([], dtype=int),
        fish_trial_mask=np.ones((len(streams), num_trials), dtype=bool),
        fish_ids=np.array([f"fish_{i}" for i in range(len(streams))]),
        duration_s=duration_s,
    )



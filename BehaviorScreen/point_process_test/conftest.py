# tests/conftest.py
"""
Shared fixtures/helpers for the point-process test suite, organized into
four layers of increasing scope and decreasing diagnostic precision:

  Layer 0 (test_layer0_known_answer.py):
      Hand-computed likelihood values, no simulation, no optimizer.
      Localizes bugs to a specific formula in _nll.

  Layer 1 (test_layer1_integral_consistency.py):
      Closed-form `integral_func`/`func` pairs cross-checked against
      scipy.integrate.quad of the SAME pointwise function. Catches
      disagreement between `evaluate` and `integrate` within one kernel.

  Layer 2 (test_layer2_independent_simulator.py):
      Data generated by a FROM-SCRATCH reference simulator that does NOT
      call simulate_stream/RateKernel/HistoryKernel at all, fit with the
      codebase's normal fit()/fit_multistart(). Directly answers "could
      simulate_stream and _nll share a bug and both be wrong the same way,"
      since this simulator shares no code with either.

  Layer 3 (test_layer3_simulation_compensator_consistency.py):
      Data generated via the codebase's OWN simulate_stream at TRUE
      (not fitted) parameters, checked via time_rescaling/Ogata's theorem
      for Uniform(0,1) residuals. No optimizer involved. Catches
      disagreement between simulate_stream's pointwise evaluate() calls
      and cumulative_integrated_intensity's integrate() calls.

  Layer 4 (test_layer4_parameter_recovery.py):
      End-to-end: simulate via simulate_stream, refit from scratch, compare
      to ground truth. Assumes Layers 0-3 already pass; this layer's job is
      to catch optimizer/parametrization/plumbing bugs, NOT likelihood
      correctness (see conversation notes on why simulate-then-fit alone is
      an insufficient test).

IMPORTANT CAVEAT ON TOLERANCES: only Layer 0's tolerances are "exact match"
(deterministic, no simulation noise). Layers 2-4 involve stochastic
simulation, so tolerances are necessarily loose and were calibrated by
inspection at the fixed seeds used here -- if you change a seed, a dataset
size, or add a parameter, re-inspect the actual |diff| vs tolerance before
trusting a pass/fail, per the assert_recovered docstring below.
"""
from typing import Dict, List, Optional

import numpy as np
import pytest

from BehaviorScreen.point_process.dataset import PointProcessDataset


